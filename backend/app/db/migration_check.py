# app/db/migration_check.py
"""
迁移漂移检测：回答一个问题 ——「实体声明的表结构」和「迁移脚本建出来的表结构」还一致吗？

为什么需要它（OPS-1 之后仍然会漂的地方）：
    有了 Alembic 也不代表不会漂：开发者改了 `entity/*.py` 的字段却忘了写迁移时，
    代码能跑、测试也过，但用户升级后库里就是少一列 —— 直到某个查询炸掉才被发现。
    `alembic check` 正是为此设计：它把「迁移建出来的库」和「ORM 元数据」对比，
    发现差异就以非零码退出。把它挂进提交流程，漂移会在**提交前**就暴露。

为什么在**临时库**上跑，而不是直接查开发者的 app.db：
    1. 开发库可能落后几个版本、或手工改过表，会产出与提交内容无关的噪音；
    2. 直接在开发库上 upgrade 会改用户数据，不该发生在"提交校验"里；
    3. 临时库从零 upgrade 到 head，检验的才是「一份干净的迁移链是否与实体一致」。
    临时库的地址通过环境变量 `APP_ALEMBIC_URL` 传给 migrations/env.py，
    见那里的说明（正常启动应用时不设这个变量，仍然用业务引擎）。

已知的、被有意忽略的差异（见 migrations/env.py 的 `_include_object`）：
    - LangGraph 自管的 checkpoints / writes：不归 ORM 管，比进来只会报"删表"；
    - SQLite 的 `INTEGER PRIMARY KEY` 可空性：SQLite 不保存 NOT NULL 标记，
      反射出来恒为 nullable=True，与 metadata 的 False 永远冲突。
"""

# 让类型注解延迟求值（PEP 563）
from __future__ import annotations

# 标准库：设置/读取环境变量（把临时库地址传给 env.py）
import os
# 标准库：临时目录，避免污染开发库
import tempfile
# 标准库：路径对象，定位 alembic.ini 与 migrations/
from pathlib import Path


# 环境变量名：migrations/env.py 见到它就改用这个数据库，而不是业务引擎
URL_ENV_VAR = "APP_ALEMBIC_URL"


def _backend_root() -> Path:
    """返回后端工程根目录（backend/）。

    本文件位于 backend/app/db/，向上三级即 backend/。

    :return: backend/ 的绝对路径
    """
    return Path(__file__).resolve().parents[2]


def _make_config():
    """构造 Alembic 配置对象（script_location 用绝对路径，避免受工作目录影响）。

    :return: alembic.config.Config 实例
    """
    # 延迟导入：alembic 是较重依赖，只有真要检查时才加载
    from alembic.config import Config

    root = _backend_root()
    config = Config(str(root / "alembic.ini"))
    config.set_main_option("script_location", str(root / "migrations"))
    return config


def check_for_drift() -> list[str]:
    """在临时库上把迁移跑到 head，然后执行 `alembic check`。

    :return: 差异描述列表；空列表表示「实体与迁移一致」
    """
    # 延迟导入：避免应用正常启动时引入 alembic 的异常类型
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected

    with tempfile.TemporaryDirectory(prefix="alembic-check-") as tmp:
        db_path = Path(tmp) / "check.db"
        previous = os.environ.get(URL_ENV_VAR)
        os.environ[URL_ENV_VAR] = f"sqlite:///{db_path.as_posix()}"
        try:
            config = _make_config()
            # 1. 从零建到最新：这一步同时验证「迁移链本身能跑通」
            command.upgrade(config, "head")
            # 2. 对比：有差异时 alembic 抛 AutogenerateDiffsDetected
            command.check(config)
            return []
        except AutogenerateDiffsDetected as exc:
            # 把异常里的多行差异拆成列表，便于 CLI 与测试逐条展示
            return [line for line in str(exc).splitlines() if line.strip()]
        finally:
            if previous is None:
                os.environ.pop(URL_ENV_VAR, None)
            else:
                os.environ[URL_ENV_VAR] = previous
